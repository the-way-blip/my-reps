// Grade to numeric for computing averages
export function gradeToNum(grade) {
  if (grade === 'A') return 4
  if (grade === 'B') return 3
  if (grade === 'C') return 2
  if (grade === 'D') return 1
  if (grade === 'F') return 0
  return null
}

export function numToGrade(num) {
  if (num >= 3.5) return 'A'
  if (num >= 2.5) return 'B'
  if (num >= 1.5) return 'C'
  if (num >= 0.5) return 'D'
  return 'F'
}

export function gradeColor(grade) {
  if (grade === 'A') return 'var(--grade-a, #22c55e)'
  if (grade === 'B') return 'var(--grade-b, #84cc16)'
  if (grade === 'C') return 'var(--grade-c, #eab308)'
  if (grade === 'D') return 'var(--grade-d, #f97316)'
  if (grade === 'F') return 'var(--grade-f, #ef4444)'
  return 'var(--text-muted)'
}
